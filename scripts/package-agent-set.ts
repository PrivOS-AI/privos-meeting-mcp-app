/**
 * Packages the Room agent's Meeting skill (`agent-sets/privos-meeting/`) as a
 * PrivOS Agent Factory agent set: `agent-sets/privos-meeting.tar.gz`, inlined
 * into the UI, which uploads it for a workspace admin (Settings → Room agent).
 *
 * As Remote Browser does it: the Sandbox names the agent set after the
 * archive's top-level directory, so only that directory carries a content hash
 * (`privos-meeting-<hash>`): a changed skill gets a new name and the Sandbox
 * extracts it fresh. The skill directory keeps its stable name, so paths in
 * SKILL.md never move. Line endings are normalised so Windows and Linux builds
 * agree on the hash. The tar is deterministic (fixed mtime/owner/order) so the
 * UI bundle, and `ui-bundle.lock.json`, only change when the skill does.
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve('agent-sets');
const skill = 'privos-meeting';
const source = path.join(root, skill, 'skills', skill);
const files = ['SKILL.md', 'scripts/meeting-tool.mjs'];
const lf = (text: string) => text.replace(/\r\n/g, '\n');
const contents = files.map((file) => lf(readFileSync(path.join(source, file), 'utf8')));

const hash = createHash('sha256');
for (const text of contents) hash.update(text).update('\0');
const name = `${skill}-${hash.digest('hex').slice(0, 8)}`;

const staging = path.join(root, '.staging');
rmSync(staging, { recursive: true, force: true });
files.forEach((file, i) => {
  const dest = path.join(staging, name, 'skills', skill, file);
  mkdirSync(path.dirname(dest), { recursive: true });
  writeFileSync(dest, contents[i], 'utf8');
});
// Relative paths + cwd: GNU/MSYS tar on Windows reads "D:" as a remote host.
const tarArgs = ['--sort=name', '--mtime=2026-01-01 00:00:00', '--owner=0', '--group=0', '--numeric-owner', '-cf', `${skill}.tar`, '-C', '.staging', name];
execFileSync('tar', tarArgs, { cwd: root });
execFileSync('gzip', ['-n', '-9', '-f', `${skill}.tar`], { cwd: root });
rmSync(staging, { recursive: true, force: true });

writeFileSync(
  path.resolve('src/ui/data/agent-set-name.ts'),
  `// Generated by scripts/package-agent-set.ts — do not edit.\n// Content-hashed agent-set name: each skill change makes the Sandbox extract it fresh.\nexport const MEETING_AGENT_SET = ${JSON.stringify(name)};\n`,
  'utf8',
);
console.log(`Packaged agent-sets/${skill}.tar.gz (agent set ${name})`);
